# ============================================================================
# FILE:       backend/app/models/user.py
# PURPOSE:    Define the `users` table: the people who own tasks. Since there
#             is no authentication, a User row is mostly an identity (name +
#             email) plus a `role` that decides admin vs. regular access.
# HOW IT WORKS: SQLAlchemy 2.0 declarative model. Type hints (`Mapped[...]`)
#             declare which columns exist; `mapped_column(...)` supplies the
#             SQL details (type, defaults, constraints, comments). Relationships
#             let you walk `user.tasks` without manual JOINs.
# USED BY / DEPENDS ON: Base from app.database, Role from schemas/common.
#             Referenced by Task, Comment, ActivityLog via foreign keys.
# KEY CONCEPTS: ORM model, primary key, UNIQUE constraint, CHECK constraint,
#             one-to-many relationship, ondelete behaviour, DB-level COMMENT.
# ============================================================================

"""SQLAlchemy model for the `users` table."""

# Mapped marks annotated attributes as table columns; mapped_column configures them.
from sqlalchemy.orm import Mapped, mapped_column, relationship

# Column types and constraints used below:
from sqlalchemy import CheckConstraint, DateTime, Identity, Integer, String, func

# datetime is the Python type that the DateTime columns deserialize into.
from datetime import datetime

# TYPE_CHECKING imports are erased at runtime: type checkers see the classes,
# Python never actually imports them (which would create circular imports).
from typing import TYPE_CHECKING

# The shared Base every model inherits from.
from app.database import Base

# Role vocabulary ("admin" | "user") — shared with the Pydantic schemas so the
# database default and the API validation can never disagree.
from app.schemas.common import Role

if TYPE_CHECKING:  # pragma: no cover - typing-only branch
    from app.models.task import Task        # for Task.user annotation
    from app.models.comment import Comment  # for Comment.user annotation


class User(Base):
    """A person who can own tasks — one row per app user.

    Real-world meaning: users register with email + password (or Google OAuth)
    and receive a JWT token. The admin user is the single row with
    role='admin'. Deleting a user cascades to their tasks and comments.

    Table: `users`
    """

    # SQL table name (plural, lowercase — a naming convention, not a rule).
    __tablename__ = "users"

    # Table-level configuration: constraints + a PostgreSQL table comment
    # (visible in psql with `\d+ users`).
    __table_args__ = (
        # Only 'admin' or 'user' may ever be stored — a CHECK constraint is the
        # database's own safety net, independent of application code.
        CheckConstraint(
            "role IN ('admin', 'user')",
            name="ck_users_role",  # named so migration logs can identify it
        ),
        # provider must be one of 'email' or 'google'.
        CheckConstraint(
            "provider IN ('email', 'google')",
            name="ck_users_provider",
        ),
        {"comment": "App identities: name + email + role + auth provider + verification state."},
    )

    # id: primary key. Identity = auto-increment generated by PostgreSQL
    # itself ("GENERATED BY DEFAULT AS IDENTITY"); never null (PK rule).
    id: Mapped[int] = mapped_column(
        Integer,
        Identity(always=True),  # sequence-backed id, insertable if needed
        primary_key=True,
    )

    # name: display name shown in headers and comment authorship.
    name: Mapped[str] = mapped_column(
        String(80),
        nullable=False,
        comment="Display name shown in UI headers and comment authorship.",
    )

    # email: unique login identifier.
    email: Mapped[str] = mapped_column(
        String(255),
        nullable=False,
        unique=True,
        comment="Unique email address used for login and OTP delivery.",
    )

    # password_hash: bcrypt hash for email/password users. Nullable because
    # Google OAuth users have no password.
    password_hash: Mapped[str | None] = mapped_column(
        String(255),
        nullable=True,
        comment="bcrypt hash of the user's password. NULL for Google OAuth users.",
    )

    # provider: 'email' (password login) or 'google' (OAuth).
    provider: Mapped[str] = mapped_column(
        String(10),
        nullable=False,
        default="email",
        server_default="email",
        comment="Authentication provider: 'email' or 'google'.",
    )

    # google_id: subject ID from Google ID token. Nullable for email users.
    google_id: Mapped[str | None] = mapped_column(
        String(255),
        nullable=True,
        unique=True,
        comment="Google subject ID for OAuth-linked accounts. NULL for email users.",
    )

    # is_verified: whether the email has been verified via OTP.
    is_verified: Mapped[bool] = mapped_column(
        nullable=False,
        default=False,
        server_default="false",
        comment="True once the user has verified their email with an OTP code.",
    )

    # email_verified_at: timestamp when verification was completed.
    email_verified_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
        comment="When the user completed email verification (UTC).",
    )

    # otp_code: the current 6-digit email OTP (stored as hashed or plain text).
    otp_code: Mapped[str | None] = mapped_column(
        String(10),
        nullable=True,
        comment="6-digit email verification code, cleared after use or expiry.",
    )

    # otp_expires_at: when the current OTP expires.
    otp_expires_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True),
        nullable=True,
        comment="OTP expiry timestamp (UTC).",
    )

    # role: 'admin' gets the admin panel; 'user' does not.
    role: Mapped[str] = mapped_column(
        String(10),
        nullable=False,
        default=Role.USER,          # Python-side default for ORM inserts
        server_default=Role.USER,   # SQL-side default for raw inserts
        comment="Permission tier: 'admin' or 'user'. Enforced by ck_users_role.",
    )

    # created_at: when the account row was born.
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
        comment="Row creation instant (UTC).",
    )

    # updated_at: refreshed automatically on row UPDATE.
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
        onupdate=func.now(),
        comment="Last modification instant (UTC).",
    )

    # --- Relationships ---------------------------------------------------
    tasks: Mapped[list["Task"]] = relationship(
        back_populates="user",
        cascade="all, delete-orphan",
        passive_deletes=True,
    )

    comments: Mapped[list["Comment"]] = relationship(
        back_populates="user",
        cascade="all, delete-orphan",
        passive_deletes=True,
    )

    def __repr__(self) -> str:
        """str: compact developer-friendly representation (not for users)."""
        return f"<User id={self.id} name={self.name!r} role={self.role!r} provider={self.provider!r}>"

    def __str__(self) -> str:
        """str: what to show in an f-string — the human name."""
        return self.name

